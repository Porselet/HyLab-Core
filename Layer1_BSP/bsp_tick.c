#define BSP_INIT_INTERNAL
#include "bsp_tick.h"

#include "stm32f1xx_ll_cortex.h"

// Системный счётчик миллисекунд (инкрементируется в SysTick_Handler)
static volatile uint32_t s_sys_tick_ms = 0U;

// ============================================================================
// ИНИЦИАЛИЗАЦИЯ SysTick НА 1 мс
// ============================================================================
#ifdef BSP_INIT_INTERNAL
void BSP_Tick_Init(void) {
    // 72 000 000 / 1000 = 72 000 тактов на 1 мс
    SysTick_Config(SystemCoreClock / 1000U);
    NVIC_SetPriority(SysTick_IRQn, 1U);
}
#endif  // BSP_INIT_INTERNAL

// ============================================================================
// ОБРАБОТЧИК ПРЕРЫВАНИЯ SysTick (1 мс)
// ============================================================================
void SysTick_Handler(void) {
    s_sys_tick_ms++;
}

// ============================================================================
// СИСТЕМНОЕ ВРЕМЯ
// ============================================================================
uint32_t BSP_GetTickMs(void) {
    return s_sys_tick_ms;
}

// ============================================================================
// БЛОКИРУЮЩАЯ ЗАДЕРЖКА (только для инициализации)
// ============================================================================
void BSP_DelayMs(uint32_t ms) {
    uint32_t start = s_sys_tick_ms;
    while ((s_sys_tick_ms - start) < ms) {
        __NOP();
    }
}